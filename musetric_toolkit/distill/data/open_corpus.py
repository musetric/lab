import csv
import json
import logging
import re
import shutil
from pathlib import Path

LOG = logging.getLogger(__name__)

CC_URLS = {
    "CC-BY-3.0": "https://creativecommons.org/licenses/by/3.0/",
    "CC-BY-4.0": "https://creativecommons.org/licenses/by/4.0/",
    "CC-BY-SA-3.0": "https://creativecommons.org/licenses/by-sa/3.0/",
    "CC-BY-SA-4.0": "https://creativecommons.org/licenses/by-sa/4.0/",
}
ALLOWED = re.compile(r"^CC-BY(-SA)?(-|$)")
PLAIN_BY = re.compile(r"^CC-BY(-\d|$)")
SHAREALIKE = re.compile(r"^CC-BY-SA")
JAMENDO_LIST = Path("sources/jamendolyrics/JamendoLyrics.csv")
JAM_ALT = "jam-alt"
REJECTED = "reject"
REJECTED_NOTE = "instrumental (no lead vocal)"
MISSING = object()
ATTRIBUTION = """# Training tracks: attribution

Every track a student here learns from, with its license and where it was
taken from. All are CC BY or CC BY-SA, which allow any use with attribution;
no NonCommercial or NoDerivatives track is in this folder. The CC BY-SA
tracks are marked: whether share-alike reaches model weights is not settled,
so they can be dropped from a training set if a release needs that.

{count} tracks. Generated by `musetric-distill data-open`.

| Artist | Title | License | Source |
| --- | --- | --- | --- |
{rows}
"""


def listed(path: Path) -> list[dict]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if isinstance(data, list):
        return data
    return next(value for value in data.values() if isinstance(value, list))


def present(entry: dict) -> dict:
    return {key: value for key, value in entry.items() if value is not MISSING}


def song_tracks(corpus: Path, leave_out: set[str]) -> list[dict]:
    tracks = []
    for song in listed(corpus / "manifest.json"):
        if song["id"] in leave_out:
            continue
        license_url = song.get("license_url")
        if license_url is None:
            license_url = CC_URLS.get(song["license"], MISSING)
        tracks.append(
            dict(
                id=song["id"],
                title=song["title"],
                artist=song["artist"],
                license=song["license"],
                licenseUrl=license_url,
                page=song.get("page_url", MISSING),
                download=song.get("download_url", MISSING),
                source=song.get("source", MISSING),
                vocals=song.get("vocals", MISSING),
                note=REJECTED_NOTE if song.get("set") == REJECTED else MISSING,
                origin=corpus / "songs" / song["file"],
            )
        )
    return tracks


def jamendo_pages(corpus: Path) -> dict[str, dict[str, str]]:
    with open(corpus / JAMENDO_LIST, encoding="utf-8", newline="") as f:
        reader = csv.reader(f)
        next(reader)
        return {
            row[1].removesuffix(".mp3"): dict(
                url=row[0], license=row[5].removeprefix("CC ").replace(" ", "-", 1)
            )
            for row in reader
        }


def lyrics_origin(song: dict, sources: dict, jamendo: dict) -> tuple[str, str, str]:
    source = sources[song["source"]]
    if song["source"] == JAM_ALT:
        row = jamendo[song["sourceName"]]
        label = f"Jamendo via {source['name']} {source['revision'].split()[0]}"
        return row["url"], f"CC-{row['license']}", label
    license_name = source["license"].removeprefix("CC ").replace(" ", "-")
    return source["url"], f"CC-{license_name}", source["name"].split(":")[0]


def lyrics_tracks(corpus: Path) -> list[dict]:
    manifest = json.loads((corpus / "manifest.json").read_text(encoding="utf-8"))
    jamendo = jamendo_pages(corpus)
    tracks = []
    for song in manifest["tracks"]:
        if not song.get("open"):
            continue
        page, license_name, source = lyrics_origin(song, manifest["sources"], jamendo)
        fallback = f"https://creativecommons.org/licenses/{license_name[3:].lower()}/"
        tracks.append(
            dict(
                id=song["id"],
                title=song["title"],
                artist=song["artist"],
                license=license_name,
                licenseUrl=CC_URLS.get(license_name, fallback),
                page=page,
                source=source,
                origin=corpus / song["mix"],
                truth_origin=corpus / song["vocals"] if song.get("vocals") else None,
            )
        )
    return tracks


def copy_once(origin: Path, target: Path) -> None:
    if not target.exists():
        shutil.copyfile(origin, target)


def place(track: dict, out: Path) -> dict:
    if not ALLOWED.match(track["license"]):
        message = f"{track['id']}: {track['license']} is not CC BY or CC BY-SA"
        raise ValueError(message)
    origin = track.pop("origin")
    truth_origin = track.pop("truth_origin", None)
    audio = f"audio/{track['id']}{origin.suffix}"
    copy_once(origin, out / audio)
    entry = {**present(track), "audio": audio}
    if truth_origin is not None:
        entry["truth"] = f"vocals/{track['id']}.flac"
        copy_once(truth_origin, out / entry["truth"])
    return entry


def attribution_row(entry: dict) -> str:
    page = entry.get("page")
    source = f"[page]({page})" if page else entry.get("source")
    link = f"[{entry['license']}]({entry.get('licenseUrl')})"
    return f"| {entry['artist']} | {entry['title']} | {link} | {source} |"


def build(args) -> None:
    leave_out = set()
    if args.leave_out:
        leave_out = set(args.leave_out.read_text(encoding="utf-8").split())
    tracks = song_tracks(args.song_corpus, leave_out)
    tracks += lyrics_tracks(args.lyrics_corpus)
    (args.out / "audio").mkdir(parents=True, exist_ok=True)
    (args.out / "vocals").mkdir(parents=True, exist_ok=True)
    manifest = [place(track, args.out) for track in tracks]
    text = json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    (args.out / "manifest.json").write_text(text, encoding="utf-8", newline="\n")
    rows = "\n".join(attribution_row(entry) for entry in manifest)
    text = ATTRIBUTION.format(count=len(manifest), rows=rows)
    (args.out / "attribution.md").write_text(text, encoding="utf-8", newline="\n")
    plain = sum(bool(PLAIN_BY.match(e["license"])) for e in manifest)
    sharealike = sum(bool(SHAREALIKE.match(e["license"])) for e in manifest)
    truth = sum("truth" in e for e in manifest)
    LOG.info(
        f"{len(manifest)} tracks: CC BY {plain}, CC BY-SA {sharealike}, "
        f"true vocals {truth}"
    )


def add_parser(commands, common) -> None:
    parser = commands.add_parser(
        "data-open",
        parents=[common],
        help="assemble the open corpus from two earlier corpora of open songs",
    )
    parser.add_argument(
        "--song-corpus",
        required=True,
        type=Path,
        help="Corpus of open songs: manifest.json (id, title, artist, license, "
        "license_url, page_url, download_url, source, file, vocals, set), songs/",
    )
    parser.add_argument(
        "--lyrics-corpus",
        required=True,
        type=Path,
        help="Corpus of open songs with lyrics: manifest.json (sources, tracks with "
        "open, source, sourceName, mix, vocals) and the JamendoLyrics list",
    )
    parser.add_argument(
        "--leave-out",
        type=Path,
        help="Ids of the song corpus also in the lyrics corpus, one per line: "
        "the lyrics corpus's copy with its true vocals is kept",
    )
    parser.add_argument(
        "--out",
        required=True,
        type=Path,
        help="Corpus directory: audio/, vocals/, manifest.json, attribution.md",
    )
    parser.set_defaults(run=build)
