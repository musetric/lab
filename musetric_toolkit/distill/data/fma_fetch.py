import ast
import csv
import json
import logging
import random
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

from musetric_toolkit.distill.corpus import dataset_rows
from musetric_toolkit.distill.data.remote_zip import fetch_members, open_archive

LOG = logging.getLogger(__name__)

LARGE_URL = "https://os.unil.cloud.switch.ch/fma/fma_large.zip"
LARGE_PREFIX = "fma_large"
CLIP_SOURCE = "Free Music Archive, FMA dataset fma_large (30 s clip)"
TRAIN_PER_GENRE = 100
HELD_MIN, HELD_MAX = 20, 30
GENRE_MIN = 40
NO_GENRE = "(none)"
SKIPPED_GENRES = (NO_GENRE, "Old-Time / Historic", "Spoken")
NOT_PERMISSIVE = ("noncommercial", "no deriv", "noderiv", "common law")
PERMISSIVE = (
    "Attribution",
    "Creative Commons Attribution",
    "CC0",
    "Public Domain Mark",
)
SPLITS = ("train", "held")
PROGRESS_EVERY = 200
WORKERS = 8
FMA_PREFIX = "fma-"
TRACK_COLUMNS = {
    "title": ("track", "title"),
    "artist": ("artist", "name"),
    "artist_id": ("artist", "id"),
    "genre_top": ("track", "genre_top"),
    "genres": ("track", "genres"),
    "seconds": ("track", "duration"),
}
RAW_COLUMNS = (
    "license_title",
    "license_url",
    "track_url",
    "track_instrumental",
    "track_bit_rate",
    "album_id",
    "album_title",
    "track_language_code",
)
ATTRIBUTION = (
    "# FMA clips: attribution\n\n"
    "30 s clips from the FMA dataset (Defferrard, Benzi, Vandergheynst, Bresson: "
    "FMA: A Dataset for Music Analysis, ISMIR 2017; https://github.com/mdeff/fma), "
    "each under its artist's license as recorded by the Free Music Archive. "
    "Only CC BY, CC BY-SA, CC0 and Public Domain Mark clips are here. "
    "{count} clips. Generated by `musetric-distill data-fma-fetch`.\n\n"
    "| Artist | Title | License | Source |\n| --- | --- | --- | --- |\n"
)


def clip_file(track_id: int) -> str:
    return f"{track_id:06d}.mp3"


def archive_member(prefix: str, track_id: int) -> str:
    return f"{prefix}/{track_id // 1000:03d}/{clip_file(track_id)}"


@dataclass
class FmaTrack:
    track_id: int
    title: str
    artist: str
    artist_id: int
    genre: str
    seconds: int
    license_title: str
    license_url: str | None
    page: str | None
    instrumental: int
    bit_rate: int | None
    album_id: str | None

    @property
    def sharealike(self) -> bool:
        return "share" in self.license_title.lower()

    @property
    def clip_id(self) -> str:
        return f"{FMA_PREFIX}{self.track_id:06d}"

    @property
    def file_name(self) -> str:
        return clip_file(self.track_id)


def read_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, data, indent: int = 1) -> None:
    text = json.dumps(data, indent=indent, ensure_ascii=False) + "\n"
    path.write_text(text, encoding="utf-8")


def permissive(license_title: str) -> bool:
    lowered = license_title.lower()
    if any(word in lowered for word in NOT_PERMISSIVE):
        return False
    return license_title.startswith(PERMISSIVE)


def raw_tracks(meta: Path) -> dict[int, dict[str, str]]:
    with open(meta / "raw_tracks.csv", encoding="utf-8", newline="") as f:
        return {
            int(row["track_id"]): {key: row[key] for key in RAW_COLUMNS}
            for row in csv.DictReader(f)
        }


def track_columns(meta: Path) -> dict[int, dict[str, str]]:
    with open(meta / "tracks.csv", encoding="utf-8", newline="") as f:
        reader = csv.reader(f)
        keys = list(zip(next(reader), next(reader), strict=True))
        next(reader)
        index = {name: keys.index(key) for name, key in TRACK_COLUMNS.items()}
        return {
            int(row[0]): {name: row[i] for name, i in index.items()} for row in reader
        }


def top_genres(meta: Path) -> dict[int, str]:
    with open(meta / "genres.csv", encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    titles = {int(row["genre_id"]): row["title"] for row in rows}
    return {int(row["genre_id"]): titles[int(row["top_level"])] for row in rows}


def genre_of(row: dict[str, str], tops: dict[int, str]) -> str:
    if row["genre_top"]:
        return row["genre_top"]
    ids = ast.literal_eval(row["genres"]) if row["genres"] else []
    return tops[ids[0]] if ids else NO_GENRE


def catalogue(meta: Path) -> list[FmaTrack]:
    tops = top_genres(meta)
    raw = raw_tracks(meta)
    out = []
    for track_id, row in track_columns(meta).items():
        extra = raw[track_id]
        if not permissive(extra["license_title"]):
            continue
        bit_rate = extra["track_bit_rate"]
        out.append(
            FmaTrack(
                track_id=track_id,
                title=row["title"],
                artist=row["artist"],
                artist_id=int(row["artist_id"]),
                genre=genre_of(row, tops),
                seconds=int(row["seconds"]),
                license_title=extra["license_title"],
                license_url=extra["license_url"] or None,
                page=extra["track_url"] or None,
                instrumental=int(extra["track_instrumental"]),
                bit_rate=int(float(bit_rate)) if bit_rate else None,
                album_id=extra["album_id"] or None,
            )
        )
    return out


def grouped(tracks: list[FmaTrack], key) -> list[tuple]:
    groups: dict = {}
    for track in tracks:
        groups.setdefault(key(track), []).append(track)
    return sorted(groups.items(), key=lambda item: item[0])


def hold_out(by_genre: list[tuple], rng: random.Random, split: dict) -> set[int]:
    held_artists = set()
    for genre, group in by_genre:
        if genre in SKIPPED_GENRES or len(group) < GENRE_MIN:
            continue
        vocal = [t for t in group if t.instrumental == 0]
        artists = sorted({t.artist_id for t in vocal})
        rng.shuffle(artists)
        count = 0
        for artist in artists:
            if count >= HELD_MIN:
                break
            ids = [t.track_id for t in vocal if t.artist_id == artist]
            ids = ids[: HELD_MAX - count]
            for track_id in ids:
                split[track_id] = "held"
            count += len(ids)
            held_artists.add(artist)
    return held_artists


def select(tracks: list[FmaTrack], seed: int) -> dict[int, str]:
    rng = random.Random(seed)  # noqa: S311
    split = {t.track_id: "pool" for t in tracks}
    by_genre = grouped(tracks, lambda t: t.genre)
    held_artists = hold_out(by_genre, rng, split)
    for _genre, group in by_genre:
        free = [
            t.track_id
            for t in group
            if split[t.track_id] == "pool" and t.artist_id not in held_artists
        ]
        rng.shuffle(free)
        for track_id in free[:TRAIN_PER_GENRE]:
            split[track_id] = "train"
    return split


def judged_trash(dataset: Path | None) -> set[int]:
    return {
        int(clip_id.removeprefix(FMA_PREFIX))
        for clip_id, row in dataset_rows(dataset).items()
        if row["decision"] == "trash" and clip_id.startswith(FMA_PREFIX)
    }


def clip_entry(track: FmaTrack, split: str) -> dict:
    return dict(
        id=track.clip_id,
        fmaId=track.track_id,
        title=track.title,
        artist=track.artist,
        license=track.license_title,
        licenseUrl=track.license_url,
        page=track.page,
        source=CLIP_SOURCE,
        audio=f"fma/{track.file_name}",
        genre=track.genre,
        instrumental=bool(track.instrumental),
        split=split,
    )


def write_attribution(corpus: Path, entries: list[dict]) -> None:
    rows = "".join(
        f"| {e['artist']} | {e['title']} | [{e['license']}]({e['licenseUrl']}) "
        f"| [page]({e['page']}) |\n"
        for e in entries
    )
    text = ATTRIBUTION.format(count=len(entries)) + rows
    path = corpus / "fma-attribution.md"
    path.write_text(text, encoding="utf-8")


def splits_of(corpus: Path, tracks: list[FmaTrack], seed: int) -> dict[int, str]:
    manifest = corpus / "fma.json"
    if not manifest.exists():
        return select(tracks, seed)
    known = {e["fmaId"]: e["split"] for e in read_json(manifest)}
    return {t.track_id: known.get(t.track_id, "pool") for t in tracks}


def fetch_clips(corpus: Path, wanted: list[FmaTrack], workers: int) -> None:
    folder = corpus / "fma"
    folder.mkdir(parents=True, exist_ok=True)
    missing = [t for t in wanted if not (folder / t.file_name).exists()]
    LOG.info(f"{len(wanted)} clips wanted, {len(missing)} to fetch")
    if not missing:
        return
    archive = open_archive(LARGE_URL)
    jobs = [
        (
            archive.getinfo(archive_member(LARGE_PREFIX, t.track_id)),
            folder / t.file_name,
        )
        for t in missing
    ]
    fetch_members(LARGE_URL, jobs, workers, PROGRESS_EVERY)


def fetch(args) -> None:
    tracks = catalogue(args.meta)
    split = splits_of(args.corpus, tracks, args.seed)
    wanted = tracks
    if args.select:
        wanted = [t for t in tracks if split[t.track_id] in SPLITS]
    trash = judged_trash(args.dataset)
    wanted = [t for t in wanted if t.track_id not in trash]
    fetch_clips(args.corpus, wanted, args.workers)
    folder = args.corpus / "fma"
    present = [t for t in tracks if (folder / t.file_name).exists()]
    entries = [clip_entry(t, split[t.track_id]) for t in present]
    write_json(args.corpus / "fma.json", entries)
    write_attribution(args.corpus, entries)
    counts = dict(Counter(e["split"] for e in entries))
    LOG.info(f"manifest: {len(entries)} clips {counts}")
    for genre, group in grouped(present, lambda t: t.genre):
        LOG.info(f"{genre}: {dict(Counter(split[t.track_id] for t in group))}")


def add_parser(commands, common) -> None:
    parser = commands.add_parser(
        "data-fma-fetch",
        parents=[common],
        help="fetch the permissively licensed 30 s clips of the FMA dataset",
    )
    parser.add_argument(
        "--meta",
        required=True,
        type=Path,
        help="Directory of the FMA metadata: tracks.csv, raw_tracks.csv, genres.csv",
    )
    parser.add_argument(
        "--corpus",
        required=True,
        type=Path,
        help="Corpus directory: clips into fma/, fma.json, fma-attribution.md",
    )
    parser.add_argument(
        "--dataset",
        type=Path,
        help="dataset.csv of the corpus: clips judged trash are never fetched again",
    )
    which = parser.add_mutually_exclusive_group(required=True)
    which.add_argument(
        "--select",
        action="store_true",
        help="Fetch the train and held-out clips (chosen anew without fma.json)",
    )
    which.add_argument("--all", action="store_true", help="Fetch every permissive clip")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--workers", type=int, default=WORKERS)
    parser.set_defaults(run=fetch)
