import csv
import json
import logging
import re
import time
from collections import Counter
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from urllib.error import HTTPError
from urllib.request import Request, urlopen

from musetric_toolkit.distill.corpus import HELD_OTHER

LOG = logging.getLogger(__name__)

AGENT = (
    "musetric-dataset/1.0 (open-source music app; "
    "+https://github.com/musetric/musetric)"
)
DELAY_SECONDS = 1.0
RETRY_SECONDS = 10
ATTEMPTS = 3
TIMEOUT_SECONDS = 120
CAP = 8
SAVE_EVERY = 50
LICENSES = {
    "http://creativecommons.org/licenses/by/2.5/": "CC-BY-2.5",
    "http://creativecommons.org/licenses/by/3.0/": "CC-BY-3.0",
    "http://creativecommons.org/licenses/by/4.0/": "CC-BY-4.0",
    "http://creativecommons.org/publicdomain/zero/1.0/": "CC0-1.0",
}
LISTING_FILES = ("all-by.csv", "all-pd.csv")
CRAWL_FILES = ("k_acap_by.json", "k_acap_cc0.json")
NO_AI_IDS = "noai_ids.txt"
SPOKEN = ",spoken_word,"
NOT_SUNG = re.compile(r",(spoken_word|poetry|podcast),")
AI = re.compile(
    r"\b(IA|AI)[ _-]?generated|by-AI|vocaloid|synth ?v\b|suno|udio", re.IGNORECASE
)
AUDIO = (".flac", ".mp3")
CCMIXTER = "ccmixter.org"
LINKED_UPLOAD = re.compile(r"ccmixter\.org/files/([^/\"']+)/(\d+)")
KEPT_TAGS = (
    "male_vocals",
    "female_vocals",
    "hip_hop",
    "rock",
    "pop",
    "electronic",
    "dry",
    "wet",
    "harmony",
    "backing_vocals",
)
SOURCE = "ccmixter.org a cappella"
FOLDER = "ccmixter-pells"
MANIFEST = "ccmixter-pells.json"
ATTRIBUTION = (
    "# ccMixter a cappellas: attribution\n\n"
    "Sung a cappellas from ccMixter (https://ccmixter.org), each under its "
    "uploader's license (CC BY or CC0). {count} uploads. Generated by "
    "`musetric-distill data-ccmixter`.\n\n"
    "| Artist | Title | License | Source |\n| --- | --- | --- | --- |\n"
)


@dataclass
class Upload:
    upload_id: int
    upload_name: str
    user_name: str
    user_real_name: str
    license_url: str
    upload_tags: str
    file_page_url: str
    main_url: str | None


def read_url(request: Request) -> bytes:
    with urlopen(request, timeout=TIMEOUT_SECONDS) as response:  # noqa: S310
        return response.read()


def get(url: str, referer: str | None = None) -> bytes:
    time.sleep(DELAY_SECONDS)
    headers = {"User-Agent": AGENT} | ({"Referer": referer} if referer else {})
    request = Request(url, headers=headers)  # noqa: S310
    for _ in range(ATTEMPTS - 1):
        try:
            return read_url(request)
        except HTTPError:
            raise
        except OSError:
            time.sleep(RETRY_SECONDS)
    return read_url(request)


def listing_uploads(folder: Path) -> list[Upload]:
    uploads = []
    for name in LISTING_FILES:
        with open(folder / name, encoding="latin-1", newline="") as f:
            uploads += [
                Upload(
                    upload_id=int(row["upload_id"]),
                    upload_name=row["upload_name"],
                    user_name=row["user_name"],
                    user_real_name=row["user_real_name"],
                    license_url=row["license_url"],
                    upload_tags=row["upload_tags"],
                    file_page_url=row["file_page_url"],
                    main_url=None,
                )
                for row in csv.DictReader(f)
                if row["license_url"] in LICENSES and SPOKEN not in row["upload_tags"]
            ]
    return uploads


def crawled(item: dict, no_ai: set[str]) -> Upload | None:
    licence = str(item["licUrl"]).replace("https://", "http://")
    audio = [f for f in item["files"] if f["name"].lower().endswith(AUDIO)]
    text = f"{item['name']} {item.get('desc', '')}"
    if (
        licence not in LICENSES
        or NOT_SUNG.search(str(item["tags"]))
        or str(item["id"]) in no_ai
        or AI.search(text)
        or not audio
    ):
        return None
    main = max(
        audio, key=lambda f: (f["name"].lower().endswith(".flac"), f.get("size") or 0)
    )
    return Upload(
        upload_id=int(item["id"]),
        upload_name=item["name"],
        user_name=item["user"],
        user_real_name=item.get("real") or "",
        license_url=licence,
        upload_tags=item["tags"],
        file_page_url=item["url"],
        main_url=main["url"],
    )


def crawl_uploads(crawl: Path, cap: int, have: dict[int, dict]) -> list[Upload]:
    no_ai = set((crawl / NO_AI_IDS).read_text(encoding="utf-8").split())
    uploads = []
    for name in CRAWL_FILES:
        for item in json.loads((crawl / name).read_text(encoding="utf-8")):
            upload = crawled(item, no_ai)
            if upload is not None:
                uploads.append(upload)
    uploads.sort(key=lambda u: -u.upload_id)
    fetched = Counter(e["uploader"] for e in have.values())
    by_user: dict[str, list[Upload]] = {}
    for upload in uploads:
        if upload.upload_id not in have:
            by_user.setdefault(upload.user_name, []).append(upload)
    return [
        upload
        for user in sorted(by_user)
        for upload in by_user[user][: max(0, cap - fetched[user])]
    ]


def capped(uploads: list[Upload], cap: int) -> list[Upload]:
    taken: Counter = Counter()
    out = []
    for upload in sorted(uploads, key=lambda u: -u.upload_id):
        if taken[upload.user_name] < cap:
            out.append(upload)
            taken[upload.user_name] += 1
    return out


def held_out_singers(corpus: Path, uploads: list[Upload]) -> set[str]:
    songs = json.loads((corpus / "manifest.json").read_text(encoding="utf-8"))
    users = set()
    for song in songs:
        if song["id"] in HELD_OTHER and CCMIXTER in (song.get("page") or ""):
            page = get(song["page"]).decode("utf-8", errors="replace")
            users |= {user for user, _ in LINKED_UPLOAD.findall(page)}
    users.discard("")
    return users & {u.user_name for u in uploads}


def excluded_artists(path: Path | None, uploads: list[Upload]) -> set[str]:
    if path is None:
        return set()
    lines = path.read_text(encoding="utf-8").splitlines()
    names = {line.strip().casefold() for line in lines if line.strip()}
    return {
        u.user_name
        for u in uploads
        if u.user_name.casefold() in names or u.user_real_name.casefold() in names
    }


def main_file(upload: Upload) -> str | None:
    if upload.main_url:
        return upload.main_url
    try:
        page = get(upload.file_page_url).decode("utf-8", errors="replace")
    except HTTPError as error:
        LOG.info(f"skip {upload.file_page_url}: {error}")
        return None
    match = re.search(rf"_ep_{upload.upload_id}'\)\.href = '([^']+)'", page)
    if not match or not match.group(1).lower().endswith(AUDIO):
        return None
    return match.group(1)


def pell_entry(upload: Upload, url: str, audio: Path) -> dict:
    tags = [t for t in str(upload.upload_tags).strip(",").split(",") if t]
    return dict(
        id=f"ccp-{upload.upload_id}",
        uploadId=upload.upload_id,
        title=upload.upload_name,
        artist=upload.user_real_name or upload.user_name,
        uploader=upload.user_name,
        license=LICENSES[upload.license_url],
        licenseUrl=upload.license_url,
        page=upload.file_page_url,
        download=url,
        source=SOURCE,
        audio=f"{FOLDER}/{audio.name}",
        tags=[t for t in tags if t in KEPT_TAGS],
    )


def save(corpus: Path, entries: dict[int, dict]) -> None:
    text = json.dumps(list(entries.values()), indent=1, ensure_ascii=False) + "\n"
    (corpus / MANIFEST).write_text(text, encoding="utf-8")


def write_attribution(corpus: Path, entries: dict[int, dict]) -> None:
    rows = "".join(
        f"| {e['artist']} | {e['title']} | [{e['license']}]({e['licenseUrl']}) "
        f"| [page]({e['page']}) |\n"
        for e in entries.values()
    )
    text = ATTRIBUTION.format(count=len(entries)) + rows
    path = corpus / "ccmixter-pells-attribution.md"
    path.write_text(text, encoding="utf-8")


def chosen_uploads(args, entries: dict[int, dict]) -> list[Upload]:
    if args.crawl:
        uploads = crawl_uploads(args.crawl, args.cap, entries)
    else:
        uploads = listing_uploads(args.listing)
    held = held_out_singers(args.corpus, uploads)
    LOG.info(f"held-out singers left out: {sorted(held)}")
    named = excluded_artists(args.exclude_artists, uploads)
    LOG.info(f"excluded artists left out: {sorted(named)}")
    uploads = [u for u in uploads if u.user_name not in held | named]
    if not args.crawl:
        uploads = capped(uploads, args.cap)
    users = len({u.user_name for u in uploads})
    LOG.info(f"{len(uploads)} uploads from {users} uploaders")
    return uploads


def fetch(args) -> None:
    manifest = args.corpus / MANIFEST
    entries = {}
    if manifest.exists():
        items = json.loads(manifest.read_text(encoding="utf-8"))
        entries = {e["uploadId"]: e for e in items}
    uploads = chosen_uploads(args, entries)
    folder = args.corpus / FOLDER
    folder.mkdir(parents=True, exist_ok=True)
    skipped = 0
    for n, upload in enumerate(uploads):
        if upload.upload_id in entries:
            continue
        url = main_file(upload)
        if url is None:
            skipped += 1
            continue
        audio = folder / f"{upload.upload_id}{PurePosixPath(url).suffix.lower()}"
        audio.write_bytes(get(url, referer=upload.file_page_url))
        entries[upload.upload_id] = pell_entry(upload, url, audio)
        if len(entries) % SAVE_EVERY == 0:
            save(args.corpus, entries)
            LOG.info(
                f"{n + 1}/{len(uploads)}: {len(entries)} fetched, {skipped} skipped "
                "(no page or no audio main file)"
            )
    save(args.corpus, entries)
    write_attribution(args.corpus, entries)
    LOG.info(
        f"done: {len(entries)} a cappellas, {skipped} skipped "
        "(no page or no audio main file)"
    )


def add_parser(commands, common) -> None:
    parser = commands.add_parser(
        "data-ccmixter",
        parents=[common],
        help="fetch sung a cappellas from ccMixter, one request a second",
    )
    parser.add_argument(
        "--corpus",
        required=True,
        type=Path,
        help="Corpus directory: manifest.json names the held-out ccMixter remix; "
        "ccmixter-pells/, ccmixter-pells.json and its attribution are written",
    )
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument(
        "--listing",
        type=Path,
        help="Directory of all-by.csv and all-pd.csv from the ccMixter query API",
    )
    source.add_argument(
        "--crawl",
        type=Path,
        help="Directory of a crawl: k_acap_by.json, k_acap_cc0.json, noai_ids.txt",
    )
    parser.add_argument(
        "--cap",
        type=int,
        default=CAP,
        help="A cappellas per uploader (with --crawl, those fetched before count)",
    )
    parser.add_argument(
        "--exclude-artists",
        type=Path,
        help="Artists never to train on, one name per line (uploader or real name), "
        "such as those of a held-out stem set",
    )
    parser.set_defaults(run=fetch)
